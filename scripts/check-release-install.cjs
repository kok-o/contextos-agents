'use strict';

// Verify the actual published surface in an isolated consumer, not source imports.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { pathToFileURL } = require('node:url');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const candidates = path.resolve(process.argv[2] || path.join(root, 'scratch/release-candidate'));
const coreVersion = require('../package.json').version;
const mcpVersion = require('../contextos-mcp/package.json').version;
const archives = [
  path.join(candidates, `contextos-agents-${coreVersion}.tgz`),
  path.join(candidates, `contextos-mcp-${mcpVersion}.tgz`),
];
for (const archive of archives) assert.ok(fs.existsSync(archive), `Pack first: ${archive}`);

function npmCli() {
  const choices = [process.env.npm_execpath,
    path.join(path.dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js')];
  for (const directory of (process.env.PATH || '').split(path.delimiter)) {
    choices.push(path.join(directory, 'node_modules/npm/bin/npm-cli.js'));
    const executable = path.join(directory, 'npm');
    if (fs.existsSync(executable)) choices.push(fs.realpathSync(executable));
  }
  const found = choices.find(file => file && file.endsWith('.js') && fs.existsSync(file));
  assert.ok(found, 'Cannot locate npm-cli.js; run through npm run check:consumer.');
  return found;
}

fs.mkdirSync(path.join(root, 'scratch'), { recursive: true });
const consumer = fs.mkdtempSync(path.join(root, 'scratch/release-consumer-space '));
const env = { ...process.env, NO_COLOR: '1', npm_config_cache: path.join(root, 'scratch/consumer-npm-cache') };
function run(executable, args, options = {}) {
  return execFileSync(executable, args, { cwd: consumer, env, encoding: 'utf8', timeout: 180000, windowsHide: true, ...options });
}
function write(relative, content) {
  const file = path.join(consumer, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
function read(relative) { return fs.readFileSync(path.join(consumer, relative), 'utf8'); }
function skillBody(source) {
  const header = source.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  assert.ok(header, 'Skill frontmatter missing');
  return source.slice(header[0].length);
}
const userAgents = '# USER AGENTS RULE\nUse the team package registry.\n';
const userClaude = '# USER CLAUDE RULE\nPreserve public API compatibility.\n';
const userCursor = 'USER CURSOR RULE\nDo not edit this file.\n';

try {
  write('package.json', JSON.stringify({ name: 'contextos-release-consumer', version: '1.0.0', private: true }));
  write('AGENTS.md', userAgents);
  write('CLAUDE.md', userClaude);
  write('.cursor/rules/team.mdc', userCursor);
  run(process.execPath, [npmCli(), 'install', '--no-audit', '--no-fund', '--ignore-scripts', '--no-package-lock', ...archives]);
  run('git', ['init', '-q']);
  // Invoke npm's real .bin wrapper, with explicit quoting on Windows.
  function wrapper(name, ...args) {
    const bin = path.join(consumer, `node_modules/.bin/${name}` + (process.platform === 'win32' ? '.cmd' : ''));
    if (process.platform !== 'win32') return run(bin, args);
    assert.ok(![bin, ...args].some(arg => /["\r\n%]/.test(arg)), 'Unsafe Windows wrapper argument');
    return run(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', `""${bin}" ${args.map(arg => `"${arg}"`).join(' ')}"`], { windowsVerbatimArguments: true });
  }
  const cli = (...args) => wrapper('contextos', ...args);
  assert.equal(JSON.parse(cli('--version', '--json')).version, coreVersion);
  assert.equal(wrapper('contextos-mcp', '--version').trim(), mcpVersion);
  cli('init', '--minimal');
  cli('skill', 'add', 'typescript');
  fs.cpSync(path.join(root, 'examples/quickstart/src'), path.join(consumer, 'src'), { recursive: true });
  fs.cpSync(path.join(root, 'examples/quickstart/team-order'), path.join(consumer, '.agents/project/skills/team-order'), { recursive: true });
  const bareRule = '---\nname: team-bare\ndescription: Manifestless team instructions\n---\n# Team\nBARE_RULE_MUST_SURVIVE\n';
  const customRule = '---\nname: team-custom\n---\n# Team\nCUSTOM_ENTRYPOINT_MUST_SURVIVE\n';
  write('.agents/project/skills/team-bare/SKILL.md', bareRule);
  write('.agents/project/skills/team-custom/skill.v2.yaml', 'schemaVersion: 2\nid: team-custom\nname: team-custom\ndescription: Canonical team instructions\ntype: instruction-only\nentrypoint: RULES.md\n');
  write('.agents/project/skills/team-custom/RULES.md', customRule);
  write('.agents/project/skills/team-custom/SKILL.md', '# Old rules\nSTALE_ENTRYPOINT_MUST_NOT_LOAD\n');
  cli('skill', 'override', 'engineering-workflow');
  const override = '.agents/project/skills/engineering-workflow/SKILL.md';
  fs.appendFileSync(path.join(consumer, override), '\nUSER OVERRIDE MARKER\n');
  cli('compile');
  cli('export', 'all');
  const drift = JSON.parse(cli('export', 'all', '--check', '--json'));
  assert.equal(drift.hasDrift, false);
  cli('update');
  const selection = JSON.parse(cli('resolve', 'Implement @team-order TypeScript validation', '--files', 'src/order.ts', '--json'));
  assert.ok(selection.selected.some(skill => skill.id === 'typescript'));
  assert.ok(selection.selected.some(skill => skill.id === 'team-order'));
  const projectedRule = read('.agents/skills/team-order/SKILL.md');
  assert.match(projectedRule, /^name: team-order\r?$/m);
  assert.equal(skillBody(projectedRule), skillBody(read('.agents/project/skills/team-order/SKILL.md')));
  assert.ok(read('.agents/skills/engineering-workflow/SKILL.md').includes('USER OVERRIDE MARKER'));
  assert.equal(skillBody(read('.agents/skills/team-bare/SKILL.md')), skillBody(bareRule));
  assert.equal(skillBody(read('.agents/skills/team-custom/SKILL.md')), skillBody(customRule));
  const loaderUrl = pathToFileURL(path.join(consumer, 'node_modules/@contextos/mcp/dist/contextos/loader.js')).href;
  run(process.execPath, ['--input-type=module', '--eval', `
    import assert from 'node:assert/strict';
    import { assembleContextPrompt } from ${JSON.stringify(loaderUrl)};
    const { prompt, report } = assembleContextPrompt(process.cwd(), 'Implement @team-bare @team-custom');
    assert.ok(prompt.includes('BARE_RULE_MUST_SURVIVE'));
    assert.ok(prompt.includes('CUSTOM_ENTRYPOINT_MUST_SURVIVE'));
    assert.ok(!prompt.includes('STALE_ENTRYPOINT_MUST_NOT_LOAD'));
    assert.ok(report.sources.some(source => source.path === '.agents/project/skills/team-custom/RULES.md'));
  `]);
  assert.equal(read('AGENTS.md'), userAgents);
  assert.ok(read('CLAUDE.md').startsWith(userClaude));
  assert.equal(read('.cursor/rules/team.mdc'), userCursor);
  console.log(run(process.execPath, [path.join(__dirname, 'check-installed-mcp.cjs'), consumer]).trim());
  assert.equal(JSON.parse(read('mcp-handshake.json')).installedVersion, mcpVersion);
  cli('uninstall', '--yes');
  assert.equal(read('AGENTS.md'), userAgents);
  assert.ok(read('CLAUDE.md').startsWith(userClaude));
  assert.equal(read('.cursor/rules/team.mdc'), userCursor);
  assert.ok(read(override).includes('USER OVERRIDE MARKER'));
  assert.ok(read('.agents/project/skills/team-order/SKILL.md').includes('Keep `createOrder` pure'));
  assert.equal(read('.agents/project/skills/team-bare/SKILL.md'), bareRule);
  assert.equal(read('.agents/project/skills/team-custom/RULES.md'), customRule);
  const result = {
    result: 'PASS', node: process.version, platform: os.platform(), coreVersion, mcpVersion,
    sourceRevision: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim(),
    archives: archives.map(file => ({ file: path.basename(file), sha256: crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex') })),
    lifecycle: ['init', 'skill add', 'override', 'compile', 'export all', 'drift check', 'update', 'resolve', 'MCP handshake', 'uninstall'],
    userInstructionsPreserved: true, userOverridePreserved: true, quickstartFixture: 'PASS',
    manifestlessAndCustomEntrypoint: 'PASS', consumerPath: consumer,
  };
  fs.writeFileSync(path.join(root, 'scratch/release-install-result.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(`Release consumer acceptance: PASS (${consumer})`);
} catch (error) {
  fs.writeFileSync(path.join(root, 'scratch/release-install-result.json'), JSON.stringify({
    result: 'FAIL', coreVersion, mcpVersion, consumerPath: consumer, error: error.message,
  }, null, 2) + '\n');
  console.error(`Release consumer acceptance: FAIL (${consumer})`);
  console.error(error.message);
  process.exitCode = 1;
}
