'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

test('core reproduces its bundle without MCP and detects drift in generated MCP copies', t => {
  const project = path.resolve(__dirname, '..');
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ctx-shared-independent-')));
  t.after(() => {
    assert.equal(path.dirname(root), fs.realpathSync(os.tmpdir()));
    assert.ok(path.basename(root).startsWith('ctx-shared-independent-'));
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5 });
  });
  for (const item of ['scripts/build-supply-chain.cjs', '.agents/transaction-core/supply-chain-src', '.agents/transaction-core/ipc-lock.js', '.agents/transaction-core/plugin-supply-chain-bundle.js']) {
    fs.mkdirSync(path.dirname(path.join(root, item)), { recursive: true });
    fs.cpSync(path.join(project, item), path.join(root, item), { recursive: true });
  }
  const run = mode => spawnSync(process.execPath, ['scripts/build-supply-chain.cjs', mode], { cwd: root, env: { ...process.env, NODE_PATH: path.join(project, 'node_modules') }, encoding: 'utf8' });
  assert.equal(fs.existsSync(path.join(root, 'contextos-mcp')), false);
  assert.equal(run('--check').status, 0);
  assert.equal(run('--write').status, 0);
  assert.equal(run('--check').status, 0);
  assert.equal(run('--check-mcp').status, 1);
  const plugins = path.join(root, 'contextos-mcp/src/plugins');
  fs.mkdirSync(plugins, { recursive: true });
  fs.cpSync(path.join(root, '.agents/transaction-core/supply-chain-src/core'), path.join(plugins, 'core'), { recursive: true });
  fs.writeFileSync(path.join(plugins, 'loader.ts'), '');
  fs.mkdirSync(path.join(root, 'contextos-mcp/src/runtime'), { recursive: true });
  assert.equal(run('--sync-mcp').status, 0);
  assert.equal(run('--check-mcp').status, 0);
  fs.appendFileSync(path.join(plugins, 'core/archive.ts'), '\n// drift\n');
  assert.match(run('--check-mcp').stderr, /generated copy differs/);
  fs.appendFileSync(path.join(root, '.agents/transaction-core/plugin-supply-chain-bundle.js'), '\n// tampered\n');
  assert.match(run('--check').stderr, /bundle is stale/);
});

test('core test runner preserves the inherited PATH when selecting Windows Bash', t => {
  const project = path.resolve(__dirname, '..');
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ctx-core-test-env-')));
  t.after(() => {
    assert.equal(path.dirname(root), fs.realpathSync(os.tmpdir()));
    assert.ok(path.basename(root).startsWith('ctx-core-test-env-'));
    fs.rmSync(root, { recursive: true, force: true });
  });
  const preload = path.join(root, 'preload.cjs');
  fs.writeFileSync(preload, `
    const cp = require('node:child_process');
    const originalPath = process.env.PATH;
    cp.spawnSync = (exe, args, options) => {
      const key = Object.keys(options.env).find(k => k.toLowerCase() === 'path');
      if (!key || !options.env[key].includes(originalPath)) throw new Error('Inherited PATH lost');
      if (options.env.CONTEXTOS_CORE_ONLY_TESTS !== '1') throw new Error('Core scope missing');
      return { status: 0 };
    };
  `);
  const run = spawnSync(process.execPath, ['--require', preload, path.join(project, 'scripts/test-core.cjs')], { encoding: 'utf8' });
  assert.equal(run.status, 0, run.stdout + run.stderr);
});

test('standalone release secret scanner reproduces and rejects stale generated bytes', t => {
  const project = path.resolve(__dirname, '..');
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ctx-release-scanner-')));
  t.after(() => {
    assert.equal(path.dirname(root), fs.realpathSync(os.tmpdir()));
    assert.ok(path.basename(root).startsWith('ctx-release-scanner-'));
    fs.rmSync(root, { recursive: true, force: true });
  });
  for (const item of ['scripts/build-release-secrets.cjs', 'scripts/check-secrets.js', 'scripts/check-release-secrets.cjs', 'bin/lib/scan.js', 'bin/lib/git-snapshot.js', 'bin/lib/secret-fixtures.json']) {
    fs.mkdirSync(path.dirname(path.join(root, item)), { recursive: true });
    fs.copyFileSync(path.join(project, item), path.join(root, item));
  }
  const run = mode => spawnSync(process.execPath, ['scripts/build-release-secrets.cjs', mode], { cwd: root, env: { ...process.env, NODE_PATH: path.join(project, 'node_modules') }, encoding: 'utf8' });
  assert.equal(run('--check').status, 0);
  fs.appendFileSync(path.join(root, 'scripts/check-release-secrets.cjs'), '\n// drift\n');
  assert.match(run('--check').stderr, /Release scanner is stale/);
  assert.equal(run('--write').status, 0);
  assert.equal(run('--check').status, 0);
});
